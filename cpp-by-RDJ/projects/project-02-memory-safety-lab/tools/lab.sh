#!/usr/bin/env bash
# Runs every buggy lab program (built with ASan+UBSan by `make all`) and writes RESULTS.md with the first
# lines of the real sanitizer reports, normalised: process ids, addresses and directory prefixes removed.
# Only runs the toy programs in this folder. Nothing here touches other processes or files.
set -u
cd "$(dirname "$0")/.."
NAMES="use_after_free heap_overflow leak double_free stack_overflow_array uninitialized_read"
OUT=RESULTS.md
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

normalise() {
  sed -E \
    -e 's/==[0-9]+==/==PID==/g' \
    -e 's#\(/[^ )]*/([^/ )]+)#(\1#g' \
    -e 's#[^ (]*/([A-Za-z_0-9]+\.cpp)#\1#g' \
    -e 's/0x[0-9a-fA-F]+/0xADDR/g'
}

{
  echo "# Lab results (real sanitizer output)"
  echo
  echo "Generated by \`make lab\` (tools/lab.sh) on this machine. Process ids, addresses and directory prefixes are"
  echo "normalised away; everything else is the sanitizer's own text. Compiler: $(g++ --version | head -1)."
  echo "Buggy programs are built with \`-std=c++20 -g -fsanitize=address,undefined\` and run as \`./prog --trigger\`."
  echo
  echo "| Program | Exit code | ASan / LSan headline | UBSan |"
  echo "|---|---|---|---|"
} > "$OUT"

DETAILS="$TMP/details"
: > "$DETAILS"
for n in $NAMES; do
  ./bin/bugs/$n --trigger > "$TMP/$n.out" 2> "$TMP/$n.err"
  code=$?
  # ASan/LSan report: the 3 lines after the first "=====" separator line
  awk 'f==0 && /^=+$/ {f=1; next} f>0 && n<3 {print; n++}' "$TMP/$n.err" | normalise > "$TMP/$n.head"
  # UBSan: its "runtime error:" lines (first two)
  grep 'runtime error:' "$TMP/$n.err" | head -2 | normalise > "$TMP/$n.ub"
  asan_kind=$(grep -m1 -oE '(AddressSanitizer|LeakSanitizer): [a-z -]+' "$TMP/$n.err" | head -1 | sed -E 's/ on( address)? *$//')
  ub_kind=$(head -1 "$TMP/$n.ub" | sed -E 's/^[^ ]+ runtime error: //')
  [ -n "$asan_kind" ] || asan_kind="none: no report"
  [ -n "$ub_kind" ] || ub_kind="none"
  echo "| \`$n\` | $code | $asan_kind | $ub_kind |" >> "$OUT"
  {
    echo "## \`bugs/$n.cpp\`"
    echo
    echo "Exit code: $code"
    echo
    if [ -s "$TMP/$n.ub" ]; then
      echo "UBSan lines:"; echo '```text'; cat "$TMP/$n.ub"; echo '```'; echo
    fi
    if [ -s "$TMP/$n.head" ]; then
      echo "First 3 lines of the sanitizer report:"; echo '```text'; cat "$TMP/$n.head"; echo '```'
    else
      echo "AddressSanitizer / LeakSanitizer printed NO report (stderr had no ===== report block)."
    fi
    echo
  } >> "$DETAILS"
done

{
  echo
  cat "$DETAILS"
  echo "## Fixed versions (\`bugs/fixed/*.cpp\`, same sanitizer flags)"
  echo
  echo "| Program | Exit code | Anything on stderr? |"
  echo "|---|---|---|"
} >> "$OUT"
for n in $NAMES; do
  ./bin/fixed/$n > "$TMP/f_$n.out" 2> "$TMP/f_$n.err"
  code=$?
  if [ -s "$TMP/f_$n.err" ]; then seen="YES (see $n)"; else seen="no (clean)"; fi
  echo "| \`fixed/$n\` | $code | $seen |" >> "$OUT"
done

{
  echo
  echo "## Extra: the one bug class ASan/UBSan miss (\`uninitialized_read\`)"
  echo
  echo "Other tools, run only if they exist and work on this machine:"
  echo
} >> "$OUT"

# Valgrind memcheck on a plain (non-sanitizer) build
if command -v valgrind > /dev/null 2>&1; then
  g++ -std=c++20 -g -O0 -o "$TMP/uninit_plain" bugs/uninitialized_read.cpp
  valgrind --error-exitcode=9 "$TMP/uninit_plain" --trigger > /dev/null 2> "$TMP/vg.err"
  vgcode=$?
  {
    echo "Valgrind memcheck (plain \`-g -O0\` build, no sanitizers), exit code $vgcode, first report:"
    echo '```text'
    grep -m1 -A2 -E 'Conditional jump|Use of uninitialised' "$TMP/vg.err" | normalise
    echo '```'
    echo
  } >> "$OUT"
else
  echo "Valgrind: not installed on this machine, not run." >> "$OUT"; echo >> "$OUT"
fi

# Clang MemorySanitizer (needs clang AND its msan runtime library)
if command -v clang++ > /dev/null 2>&1 && clang++ -std=c++20 -g -O0 -fsanitize=memory -o "$TMP/uninit_msan" bugs/uninitialized_read.cpp 2> "$TMP/msan_build.err"; then
  "$TMP/uninit_msan" --trigger > /dev/null 2> "$TMP/msan.err"
  mcode=$?
  {
    echo "Clang MemorySanitizer, exit code $mcode, first lines:"
    echo '```text'
    head -3 "$TMP/msan.err" | normalise
    echo '```'
  } >> "$OUT"
else
  echo "Clang MemorySanitizer: NOT run. Either clang is missing or its msan runtime library is not installed here (the build failed)." >> "$OUT"
fi
echo "wrote $OUT"
